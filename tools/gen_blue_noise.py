#!/usr/bin/env python3
"""Makes the 64x64 blue-noise threshold mask for the picture dither, with
Ulichney's void-and-cluster method, and writes it as C++.

  python3 tools/gen_blue_noise.py core/src/image/blue_noise.cpp

The mask is computed here from a fixed seed (no published texture is used),
so running it again gives the same file.
"""
import math
import random
import sys

N = 64
SIGMA = 1.5


def kernel():
    """Gaussian weight for every wrapped offset (dy * N + dx)."""
    k = [0.0] * (N * N)
    for dy in range(N):
        for dx in range(N):
            ddy, ddx = min(dy, N - dy), min(dx, N - dx)
            k[dy * N + dx] = math.exp(-(ddx * ddx + ddy * ddy) / (2 * SIGMA * SIGMA))
    return k


K = kernel()


def add(energy, p, sign):
    py, px = divmod(p, N)
    for y in range(N):
        row = ((y - py) % N) * N
        base = y * N
        for x in range(N):
            energy[base + x] += sign * K[row + (x - px) % N]


def energy_of(ones):
    e = [0.0] * (N * N)
    for p in range(N * N):
        if ones[p]:
            add(e, p, 1)
    return e


def tightest(ones, e):
    return max((p for p in range(N * N) if ones[p]), key=lambda p: e[p])


def largest_void(ones, e):
    return min((p for p in range(N * N) if not ones[p]), key=lambda p: e[p])


def mask():
    rng = random.Random(1998)
    ones = [False] * (N * N)
    for p in rng.sample(range(N * N), N * N // 10):
        ones[p] = True
    e = energy_of(ones)
    # Spread the starting points: move the tightest cluster into the largest
    # void until that would put it straight back.
    while True:
        c = tightest(ones, e)
        ones[c] = False
        add(e, c, -1)
        v = largest_void(ones, e)
        if v == c:
            ones[c] = True
            add(e, c, 1)
            break
        ones[v] = True
        add(e, v, 1)
    start = list(ones)
    start_e = list(e)
    count = sum(ones)
    rank = [0] * (N * N)
    # Phase 1: take the starting points away, tightest first: lower ranks.
    r = count
    while r > 0:
        c = tightest(ones, e)
        ones[c] = False
        add(e, c, -1)
        r -= 1
        rank[c] = r
    # Phase 2 and 3: fill the largest voids: higher ranks.
    ones, e = start, start_e
    for r in range(count, N * N):
        v = largest_void(ones, e)
        ones[v] = True
        add(e, v, 1)
        rank[v] = r
    return rank


def main():
    rank = mask()
    assert sorted(rank) == list(range(N * N))
    with open(sys.argv[1], "w") as f:
        f.write("// Generated by tools/gen_blue_noise.py (void and cluster, seed 1998,\n")
        f.write("// sigma %.1f); do not edit. Thresholds 0..4095 for a 64x64 tile.\n" % SIGMA)
        f.write('#include "blue_noise.hpp"\n\nnamespace image {\n\n')
        f.write("const uint16_t kBlueNoise[64 * 64] = {\n")
        for y in range(N):
            f.write("    " + ", ".join("%d" % v for v in rank[y * N:(y + 1) * N]) + ",\n")
        f.write("};\n\n} // namespace image\n")


if __name__ == "__main__":
    main()
