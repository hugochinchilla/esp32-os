#!/usr/bin/env python3
"""Turns a fixed-size BDF font into a C++ table for the core's text drawing.

  python3 tools/gen_font.py third_party/fonts/spleen/spleen-6x12.bdf \
      core/src/gfx/font_spleen6x12.cpp

Covers character codes 0 to 255 (ASCII and Latin-1); codes the font lacks are
left blank. Every glyph must have the same size, as Spleen's do. One byte per
row, leftmost pixel in bit 7.

Wider fonts, only some characters (for the start-up screens):

  python3 tools/gen_font.py third_party/fonts/spleen/spleen-32x64.bdf \
      core/src/gfx/font_spleen32x64.cpp kSpleen32x64 "Chinal"

writes a gfx::WideFont with just those characters, (width + 7) / 8 bytes
per row.
"""
import os
import sys


def read_bdf(path):
    glyphs, cur, rows = {}, None, None
    box = None
    for line in open(path, encoding="latin-1"):
        p = line.split()
        if not p:
            continue
        k = p[0]
        if k == "FONTBOUNDINGBOX":
            box = tuple(int(v) for v in p[1:5])
        elif k == "STARTCHAR":
            cur = {}
        elif k == "ENCODING":
            cur["code"] = int(p[1])
        elif k == "BBX":
            cur["bbx"] = tuple(int(v) for v in p[1:5])
        elif k == "BITMAP":
            rows = []
        elif k == "ENDCHAR":
            cur["rows"] = rows
            glyphs[cur["code"]] = cur
            cur = rows = None
        elif rows is not None:
            rows.append(int(k, 16) << (8 - 4 * len(k)) if len(k) <= 2 else int(k[:2], 16))
    return box, glyphs


def read_wide(path):
    """Glyphs of any width: code -> list of rows as (bits, bit count)."""
    glyphs, rows, code, box = {}, None, None, None
    for line in open(path, encoding="latin-1"):
        p = line.split()
        if not p:
            continue
        if p[0] == "FONTBOUNDINGBOX":
            box = int(p[1]), int(p[2])
        elif p[0] == "ENCODING":
            code = int(p[1])
        elif p[0] == "BITMAP":
            rows = []
        elif p[0] == "ENDCHAR":
            glyphs[code] = rows
            rows = None
        elif rows is not None:
            rows.append((int(p[0], 16), len(p[0]) * 4))
    return box, glyphs


def main_wide(src, out, name, chars):
    (width, height), glyphs = read_wide(src)
    per_row = (width + 7) // 8
    chars = "".join(sorted(set(chars)))
    data = []
    for ch in chars:
        rows = glyphs[ord(ch)]
        assert len(rows) == height, ch
        line = []
        for bits, nb in rows:
            v = bits << (per_row * 8 - nb) if nb <= per_row * 8 else bits >> (nb - per_row * 8)
            line += [(v >> (8 * (per_row - 1 - i))) & 0xFF for i in range(per_row)]
        data.append("    // %r\n    %s," % (ch, ", ".join("0x%02X" % b for b in line)))
    base = os.path.basename(src)
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_font.py from third_party/fonts/spleen/%s, only\n" % base)
        f.write("// the characters %r. Do not edit. Spleen: Copyright (c) 2018-2026\n" % chars)
        f.write("// Frederic Cambus, BSD 2-Clause licence (third_party/fonts/spleen/LICENSE).\n")
        f.write('#include "core/gfx/font.hpp"\n\nnamespace gfx {\n\nnamespace {\n\n')
        f.write("const uint8_t kGlyphs[] = {\n%s\n};\n\n} // namespace\n\n" % "\n".join(data))
        f.write('const WideFont %s = {%d, %d, %d, "%s", kGlyphs};\n\n} // namespace gfx\n'
                % (name, width, height, per_row, chars.replace("\\", "\\\\").replace('"', '\\"')))


def main():
    if len(sys.argv) == 5:
        main_wide(*sys.argv[1:5])
        return
    src, out = sys.argv[1], sys.argv[2]
    box, glyphs = read_bdf(src)
    width, height = box[0], box[1]
    assert width <= 8, "one byte per row"
    lines = []
    for code in range(256):
        g = glyphs.get(code)
        if g is None:
            rows = [0] * height
        else:
            assert g["bbx"] == box, "glyph %d is not %dx%d" % (code, width, height)
            rows = g["rows"]
        lines.append("    {%s}, // %s" % (", ".join("0x%02X" % r for r in rows),
                                         repr(chr(code)) if 32 <= code < 127 or code >= 160 else code))
    name = "spleen-6x12"
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_font.py from third_party/fonts/spleen/%s.bdf.\n" % name)
        f.write("// Do not edit. Spleen: Copyright (c) 2018-2026 Frederic Cambus, BSD 2-Clause\n")
        f.write("// licence (third_party/fonts/spleen/LICENSE).\n")
        f.write('#include "core/gfx/font.hpp"\n\nnamespace gfx {\n\nnamespace {\n\n')
        f.write("const uint8_t kGlyphs[256][%d] = {\n" % height)
        f.write("\n".join(lines))
        f.write("\n};\n\n} // namespace\n\n")
        f.write("const Font kSpleen6x12 = {%d, %d, &kGlyphs[0][0]};\n\n} // namespace gfx\n" % (width, height))


if __name__ == "__main__":
    main()
